/// 相册（选图能力）。
///
/// ## 为什么值得单独抽一个接口，而不是在 UI 里直接调 `image_picker`
///
/// 三个理由，任何一个都足够：
///  1. **测试**：插件依赖平台通道，在 `flutter test` 里根本调不通。
///     收敛成接口后，测试传一个假实现就完事（见 `MockPhotoLibrary`）。
///  2. **多端**：桌面端 / Web 的相册实现完全不同，UI 不该知道这个差异。
///  3. **上传**：真实链路是"选图 → 拿到本地临时文件 → 上传 → 换成远端地址"。
///     把这四步封装在实现里，调用方拿到的永远是"能直接放进动态的地址"，
///     于是发帖面板在 Mock 阶段和真实阶段**一行都不用改**。
abstract interface class PhotoLibrary {
  /// 让用户挑图，返回可以放进动态的图片地址。
  ///
  /// [maxCount] 是本次最多能挑几张（受九宫格上限约束），实现方必须尊重它 ——
  /// 由调用方截断是危险的，因为"已经选了几张"只有调用方知道。
  ///
  /// **用户取消时返回空列表，不抛异常**：取消是正常操作，不是错误。
  /// 把它当异常处理会让每个调用点都多一个 try/catch，还容易误报"选图失败"。
  Future<List<String>> pickImages({required int maxCount});
}
